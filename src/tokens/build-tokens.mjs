import { mkdir, readFile, writeFile } from 'node:fs/promises';

import { expandTypesMap, register } from '@tokens-studio/sd-transforms';
import StyleDictionary from 'style-dictionary';

const project = new URL('../../', import.meta.url);
const readJson = async (path) =>
  JSON.parse(await readFile(new URL(path, project), 'utf8'));
const {
  source: [sourceFile],
  ...config
} = await readJson('config/sd.config.json');
const source = await readJson(sourceFile);
const output = new URL(config.platforms.css.buildPath, project);
const generated = 'Generated by npm run tokens:build. Do not edit.';

await register(StyleDictionary);

async function resolveTheme(name) {
  const theme = source.$themes.find((entry) => entry.name === name);
  if (theme?.selectedTokenSets?.[name] !== 'enabled') {
    throw new Error(`Missing enabled token set for theme "${name}".`);
  }

  const { global, semantic } = source;
  // Global and semantic share the Figma color group. Only publish the
  // semantic role names selected by the light and dark theme sets.
  const dictionary = new StyleDictionary({
    ...config,
    expand: { typesMap: expandTypesMap },
    tokens: {
      ...global,
      ...semantic,
      ...source[name],
      color: { ...global.color, ...semantic.color },
    },
  });
  const { allTokens } = await dictionary.getPlatformTokens('css');

  return allTokens;
}

const [light, dark] = await Promise.all([
  resolveTheme('default-light'),
  resolveTheme('default-dark'),
]);

const groups = {
  spacing: { source: 'space', prefix: 'space' },
  fontFamilies: { source: ['font-family', 'fontFamily'], prefix: 'ff' },
  fontSizes: { source: 'font-size', prefix: 'fs' },
  fontWeights: { source: 'font-weight', prefix: 'fw' },
  lineHeights: { source: 'line-height', prefix: 'lh' },
  letterSpacings: { source: 'letter-spacing', prefix: 'ls' },
  radius: { source: 'radius', prefix: 'r' },
  borderWidths: { source: 'border', prefix: 'bw' },
  opacity: { source: 'opacity', prefix: 'op' },
  motion: { source: 'motion', prefix: 'mo' },
};

function cssValue(token, convertPixels = true) {
  const { value, path } = token;
  if (typeof value !== 'string' && typeof value !== 'number') {
    throw new Error(`Expected a scalar value for "${path.join('.')}".`);
  }
  if (convertPixels && typeof value === 'string' && value.endsWith('px')) {
    return `${parseFloat(value) / 16}rem`;
  }

  return value;
}

function groupValues(tokens, group, convertPixels = true) {
  const names = [group].flat();

  return Object.fromEntries(
    tokens
      .filter(({ path }) => names.includes(path[0]))
      .map((token) => [token.path[1], cssValue(token, convertPixels)]),
  );
}

const values = Object.fromEntries(
  Object.entries(groups).map(([name, group]) => [
    name,
    groupValues(light, group.source, name !== 'borderWidths'),
  ]),
);

const colors = {
  light: groupValues(light, 'theme-color'),
  dark: groupValues(dark, 'theme-color'),
};
if (
  Object.keys(colors.light).sort().join() !==
  Object.keys(colors.dark).sort().join()
) {
  throw new Error('Light and dark themes must define the same color roles.');
}

const breakpoints = {};
for (const [name, value] of Object.entries(groupValues(light, 'breakpoint'))) {
  breakpoints[name] = { 'min-width': value };
  if (['md', 'lg', 'xl'].includes(name)) {
    breakpoints[`${name}-down`] = {
      'max-width': `${parseFloat(value) - 0.05}rem`,
    };
  }
}

const typographyProperties = {
  fontFamily: 'font-family',
  fontSize: 'font-size',
  fontWeight: 'font-weight',
  lineHeight: 'line-height',
  letterSpacing: 'letter-spacing',
  textCase: 'text-transform',
  textDecoration: 'text-decoration',
};
const typography = {};
for (const token of light) {
  const [group, ...path] = token.path;
  if (!['typography', 'FontPrimary', 'FontSecondary'].includes(group)) {
    continue;
  }

  // Figma includes paragraph spacing, which has no direct CSS property.
  const property = typographyProperties[path.pop()];
  if (property) {
    const style = [group, ...path]
      .join('-')
      .replace(/^(typography-|Font)/, '')
      .toLowerCase();
    typography[style] ??= {};
    typography[style][property] = cssValue(token);
  }
}

function sassMap(entries, indent = '', numericKeys = false) {
  const body = Object.entries(entries).map(([key, value]) => {
    const name = numericKeys && /^\d+$/.test(key) ? key : `'${key}'`;
    const property =
      typeof value === 'object' ? sassMap(value, `${indent}  `) : value;
    return `${indent}  ${name}: ${property},`;
  });
  return `(\n${body.join('\n')}\n${indent})`;
}

const maps = [
  ['spacings', values.spacing, true],
  ['breakpoints', breakpoints],
  ['font-families', values.fontFamilies],
  ['font-sizes', values.fontSizes],
  ['font-weights', values.fontWeights],
  ['line-heights', values.lineHeights],
  ['letter-spacings', values.letterSpacings, true],
  ['typography', typography],
].map(
  ([name, entries, numericKeys]) =>
    `$${name}: ${sassMap(entries, '', numericKeys)};`,
);

function customProperties(prefix, entries) {
  return Object.entries(entries).map(([name, value]) => {
    const css = String(value).replace(
      /^#([\da-f])\1([\da-f])\2([\da-f])\3$/i,
      '#$1$2$3',
    );
    return `  --${prefix}-${name}: ${css};`;
  });
}

function themeSelector(variation) {
  return `[data-component-theme~='${variation}']`;
}

const css = [
  `:root,\n${themeSelector('light')} {`,
  ...customProperties('clr', colors.light),
  '}',
  '',
  ':root {',
  ...Object.entries(groups).flatMap(([name, { prefix }]) =>
    customProperties(prefix, values[name]),
  ),
  '}',
  '',
  `${themeSelector('dark')} {`,
  ...customProperties('clr', colors.dark),
  '}',
].join('\n');

await mkdir(output, { recursive: true });
await Promise.all([
  writeFile(
    new URL('_maps.scss', output),
    `// ${generated}\n\n${maps.join('\n')}\n`,
  ),
  writeFile(
    new URL('_custom-properties.scss', output),
    `// ${generated}\n\n${css}\n`,
  ),
  writeFile(
    new URL('tokens.json', output),
    `${JSON.stringify({ $comment: generated, colors, ...values, breakpoints, typography }, null, 2)}\n`,
  ),
]);
